cask "desktop-name-manager" do
  version "0.4.0"
  sha256 "c7c477a71ae84ea93eab6f07a002dba566017238d9471fa0e5bc6da803aedbd7"

  url "https://github.com/inquinity/desktop-name-manager/releases/download/v#{version}/desktop-name-manager-#{version}-arm64.zip"
  name "Desktop Name Manager"
  desc "Label each Desktop (Space) by stamping its name into the wallpaper"
  homepage "https://github.com/inquinity/desktop-name-manager"

  livecheck do
    url :url
    strategy :github_latest
  end

  depends_on arch: :arm64
  depends_on macos: :tahoe

  # The app, and dnm (also as desktop-name), which runs from inside the app and is the same tool as the standalone one.
  app "Desktop Name Manager.app"
  # A running menu-bar app is asked to quit before an upgrade or uninstall replaces it.
  uninstall quit: "com.altmansoftwaredesign.desktop-name-manager"
  binary "#{appdir}/Desktop Name Manager.app/Contents/Helpers/dnm"
  binary "#{appdir}/Desktop Name Manager.app/Contents/Helpers/dnm", target: "desktop-name"

  # Shell completions, generated by the released binary (spec 007): one zsh file per command name, and one bash
  # file that registers both.
  zsh_completion "completions/_dnm"
  zsh_completion "completions/_desktop-name"
  bash_completion "completions/dnm.bash", target: "dnm"

  # No zap stanza: labeled Desktops may still show images from the store, so it is never deleted
  # automatically. See "Full removal" in the README.

  caveats <<~EOS
    The app (Desktop Name Manager) sits in the menu bar and labels the Desktop on screen; it needs no
    permission. `dnm` and `desktop-name` are installed too.

    Labeling the Desktop on screen needs no permission. `dnm --desktop N` needs the
    Accessibility permission: macOS grants it to the whole app you run dnm from (your terminal), so every program run in that app can then send keystrokes and clicks too; turn it off when you no longer need --desktop or cleanup --scan.

    Uninstalling removes the app and keeps your wallpapers and the stored labels. For full removal, see
      https://github.com/inquinity/desktop-name-manager#uninstall
  EOS
end
